[query_table_names]
SELECT TABLE_NAME FROM ALL_TABLES WHERE OWNER = ? AND UPPER(TABLE_NAME) LIKE ? ORDER BY TABLE_NAME DESC

[query_table_create]
SELECT dbms_metadata.get_ddl('TABLE', '${tableName}', '${owner}') AS table_ddl FROM DUAL

[query_table_comments]
SELECT COLUMN_NAME,COMMENTS FROM ALL_COL_COMMENTS WHERE OWNER = ? AND TABLE_NAME = ? AND COMMENTS IS NOT NULL

[query_table_table_comment]
SELECT COMMENTS FROM ALL_TAB_COMMENTS WHERE OWNER = ? AND TABLE_NAME = ? AND COMMENTS IS NOT NULL

[query_table_constraint_indexes]
SELECT INDEX_NAME FROM ALL_CONSTRAINTS WHERE OWNER = ? AND TABLE_NAME = ? AND CONSTRAINT_TYPE IN ('P','U') AND INDEX_NAME IS NOT NULL

[query_table_indexes]
SELECT INDEX_NAME FROM ALL_INDEXES WHERE OWNER = ? AND TABLE_NAME = ? AND INDEX_TYPE <> 'LOB'

[query_table_index_create]
SELECT dbms_metadata.get_ddl('INDEX', '${indexName}', '${owner}') AS index_ddl FROM DUAL

[query_table_triggers]
SELECT TRIGGER_NAME FROM ALL_TRIGGERS WHERE OWNER = ? AND TABLE_NAME = ?

[query_table_trigger_create]
SELECT TEXT FROM ALL_SOURCE WHERE OWNER = ? AND TYPE='TRIGGER' AND NAME=? ORDER BY LINE
